// Short aliases are whole tokens, not substrings such as CAN in Canada or SEA in overseas.
const token = (pattern: string) => new RegExp(
  String.raw`(?<![\p{Script=Latin}\p{N}])(?:${pattern})(?![\p{Script=Latin}\p{N}])`, 'iu',
);
const cityIndex = CITIES.map(([regionCode, cityZh, cityEn, lng, lat, aliases]) => ({
  location: { regionCode, cityZh, cityEn, lng, lat },
  full: token(cityEn.replaceAll(' ', '[ ._-]*')),
  alias: aliases && token(aliases),
}));
const regionZh = new Intl.DisplayNames('zh-CN', { type: 'region' });
const regionEn = new Intl.DisplayNames('en', { type: 'region' });

export function resolveNodeGeo(client: KomariClient): GeoLocation | null {
  if (!client.region?.trim()) return null;
  const regionCode = parseRegion(client.region);
  const name = client.name;
  const remark = client.public_remark ?? '';
  const city = cityIndex.find(({ location, full }) => name.includes(location.cityZh) || full.test(name))
    ?? cityIndex.find(({ location, full }) => remark.includes(location.cityZh) || full.test(remark))
    ?? cityIndex.find(({ alias }) => alias && alias.test(name))
    ?? cityIndex.find(({ alias }) => alias && alias.test(remark));
  if (city) return { ...city.location };
  if (!Object.hasOwn(COUNTRY_COORDINATES, regionCode)) return null;
  const [lng, lat] = COUNTRY_COORDINATES[regionCode];
  return { lng, lat, cityZh: regionZh.of(regionCode) ?? regionCode, cityEn: regionEn.of(regionCode) ?? regionCode, regionCode };
}
